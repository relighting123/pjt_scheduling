-- @db: Prd
-- 이미 RTS_RSLT_MAS/HIS 등이 배포된 운영 DB에 RTS_TRACE_INF/HIS 테이블만 추가하는
-- 마이그레이션. rts_output_tables.sql의 정의와 동일 — 신규 설치(db-load --ddl-only)에는
-- 이 파일이 필요 없다(rts_output_tables.sql이 이미 포함). 기존 배포에만 1회 실행한다.

CREATE TABLE RTS_TRACE_INF (
    FAC_ID              VARCHAR2(32)   NOT NULL,
    RULE_TIMEKEY        VARCHAR2(14)   NOT NULL,
    EQP_ID              VARCHAR2(64)   NOT NULL,
    CARRIER_ID          VARCHAR2(64)   NOT NULL,
    CANDIDATE_PPK       VARCHAR2(64)   NOT NULL,
    CANDIDATE_OPER_ID   VARCHAR2(64)   NOT NULL,
    IS_SELECTED         CHAR(1)        DEFAULT 'N' NOT NULL,
    WIP_SHARE           NUMBER(6,4),
    URGENCY             NUMBER(6,4),
    COVERAGE_RATIO      NUMBER(6,4),
    STARVE_NORM         NUMBER(6,4),
    NEEDS_CONV          CHAR(1),
    AVOIDABLE_FRAC      NUMBER(6,4),
    SETUP_CHANGED       CHAR(1),
    CRT_USER_ID         VARCHAR2(32)   DEFAULT 'RTS' NOT NULL,
    CRT_TM              TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    EXEC_TIMEKEY        VARCHAR2(14)   NOT NULL,
    CONSTRAINT PK_RTS_TRACE_INF PRIMARY KEY
        (FAC_ID, RULE_TIMEKEY, EQP_ID, CARRIER_ID, CANDIDATE_PPK, CANDIDATE_OPER_ID)
);

CREATE INDEX IX_RTS_TRACE_INF_FAC ON RTS_TRACE_INF (FAC_ID, RULE_TIMEKEY);

CREATE TABLE RTS_TRACE_HIS (
    FAC_ID              VARCHAR2(32)   NOT NULL,
    RULE_TIMEKEY        VARCHAR2(14)   NOT NULL,
    EQP_ID              VARCHAR2(64)   NOT NULL,
    CARRIER_ID          VARCHAR2(64)   NOT NULL,
    CANDIDATE_PPK       VARCHAR2(64)   NOT NULL,
    CANDIDATE_OPER_ID   VARCHAR2(64)   NOT NULL,
    IS_SELECTED         CHAR(1)        DEFAULT 'N' NOT NULL,
    WIP_SHARE           NUMBER(6,4),
    URGENCY             NUMBER(6,4),
    COVERAGE_RATIO      NUMBER(6,4),
    STARVE_NORM         NUMBER(6,4),
    NEEDS_CONV          CHAR(1),
    AVOIDABLE_FRAC      NUMBER(6,4),
    SETUP_CHANGED       CHAR(1),
    CRT_USER_ID         VARCHAR2(32)   DEFAULT 'RTS' NOT NULL,
    CRT_TM              TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    EXEC_TIMEKEY        VARCHAR2(14)   NOT NULL,
    CONSTRAINT PK_RTS_TRACE_HIS PRIMARY KEY
        (FAC_ID, EXEC_TIMEKEY, RULE_TIMEKEY, EQP_ID, CARRIER_ID, CANDIDATE_PPK, CANDIDATE_OPER_ID)
);

CREATE INDEX IX_RTS_TRACE_HIS_FAC ON RTS_TRACE_HIS (FAC_ID, RULE_TIMEKEY);
